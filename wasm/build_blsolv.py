#!/usr/bin/env python3
"""Build the standalone, strict-double BLSOLV kernel (Clang/LLD with wasm32).

The generated ES module is committed so static hosting needs no build step,
extra binary fetch, or Emscripten runtime. Rebuild after changing the C++ source.
"""

import argparse
import base64
import hashlib
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', default='clang++')
    parser.add_argument('--linker', default='wasm-ld')
    args = parser.parse_args()
    source = Path(__file__).resolve().with_name('blsolv_kernel.cpp')
    output = source.parent.parent / 'js' / 'blsolv_wasm_data.js'
    with tempfile.TemporaryDirectory(prefix='blsolv-build-') as directory:
        obj = Path(directory) / 'blsolv.o'
        binary = Path(directory) / 'blsolv.wasm'
        subprocess.run([
            args.compiler, '--target=wasm32', '-O3', '-msimd128',
            '-fno-fast-math', '-ffp-contract=off', '-nostdlib',
            '-c', str(source), '-o', str(obj),
        ], check=True)
        subprocess.run([
            args.linker, '--no-entry', '--export=blsolv_flat',
            '--export=__heap_base', '--export-memory', '-z', 'stack-size=0',
            '--initial-memory=65536', '--max-memory=67108864', '--strip-all',
            str(obj), '-o', str(binary),
        ], check=True)
        data = binary.read_bytes()
    encoded = base64.b64encode(data).decode('ascii')
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    lines = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
    output.write_text(
        '// Generated by wasm/build_blsolv.py; do not edit. GPL-2.0-or-later.\n'
        f"export const sourceSha256 = '{digest}';\n"
        'export const blsolvBase64 =\n'
        + ' +\n'.join(f"  '{line}'" for line in lines) + ';\n'
    )
    print(f'Built {output.name}: {len(data):,} WebAssembly bytes')


if __name__ == '__main__':
    main()
