#!/usr/bin/env python3
"""Generate and compile the current JS boundary-layer equations to strict Wasm."""
import argparse
import base64
import hashlib
import pathlib
import subprocess
import tempfile

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', default='clang++')
    parser.add_argument('--linker', default='wasm-ld')
    args = parser.parse_args()
    here = pathlib.Path(__file__).resolve().parent
    subprocess.run(['node', str(here / 'generate_boundary_layer.mjs')], check=True)
    source = here / 'boundary_layer_generated.cpp'
    with tempfile.TemporaryDirectory(prefix='vibefoil-bl-wasm-') as directory:
        obj = pathlib.Path(directory) / 'boundary_layer.o'
        binary = pathlib.Path(directory) / 'boundary_layer.wasm'
        subprocess.run([args.compiler, '--target=wasm32', '-std=c++20', '-O3',
                        '-fno-fast-math', '-ffp-contract=off', '-fno-strict-aliasing',
                        '-fno-builtin', '-nostdlib',
                        '-Wno-tautological-compare', '-c', str(source), '-o', str(obj)], check=True)
        matrix = pathlib.Path(directory) / 'blsolv.o'
        subprocess.run([args.compiler, '--target=wasm32', '-O3', '-msimd128',
                        '-fno-fast-math', '-ffp-contract=off', '-nostdlib',
                        '-c', str(here / 'blsolv_kernel.cpp'), '-o', str(matrix)], check=True)
        subprocess.run([args.linker, '--no-entry', '--export=boundary_layer', '--export=boundary_layer_step',
                        '--export=__heap_base', '--export-memory', '-z', 'stack-size=262144',
                        '--initial-memory=327680', '--max-memory=67108864', '--strip-all',
                        str(obj), str(matrix), '-o', str(binary)], check=True)
        data = binary.read_bytes()
    sources = [source, here / 'boundary_layer_runtime.h', here / 'boundary_layer_step.h', here / 'blsolv_kernel.cpp', here / 'generate_boundary_layer.mjs',
               here / 'build_boundary_layer.py', here.parent / 'js/boundary_layer_layout.js']
    hashes = {str(p.relative_to(here.parent)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources}
    import json
    encoded = base64.b64encode(data).decode('ascii')
    lines = [encoded[i:i+100] for i in range(0, len(encoded), 100)]
    (here.parent / 'js/boundary_layer_wasm_data.js').write_text(
        '// Generated by wasm/build_boundary_layer.py. GPL-2.0-or-later.\n'
        + 'export const sourceHashes = ' + json.dumps(hashes, indent=2) + ';\n'
        + 'export const boundaryLayerBase64 =\n' + ' +\n'.join(repr(line) for line in lines) + ';\n')
    print(f'Built boundary-layer kernel: {len(data):,} bytes')

if __name__ == '__main__':
    main()
