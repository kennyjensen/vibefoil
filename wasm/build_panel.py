#!/usr/bin/env python3
"""Build strict-double panel LU and back-substitution without a runtime."""
import argparse
import base64
import hashlib
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', default='clang++')
    parser.add_argument('--linker', default='wasm-ld')
    args = parser.parse_args()
    source = Path(__file__).resolve().with_name('panel_kernel.cpp')
    output = source.parent.parent / 'js/panel_wasm_data.js'
    with tempfile.TemporaryDirectory(prefix='vibefoil-panel-wasm-') as directory:
        obj = Path(directory) / 'panel.o'
        binary = Path(directory) / 'panel.wasm'
        subprocess.run([
            args.compiler, '--target=wasm32', '-O3', '-msimd128',
            '-fno-fast-math', '-ffp-contract=off', '-nostdlib',
            '-c', str(source), '-o', str(obj),
        ], check=True)
        subprocess.run([
            args.linker, '--no-entry', '--export=panel_lu', '--export=panel_solve',
            '--export=__heap_base', '--export-memory', '-z', 'stack-size=0',
            '--initial-memory=65536', '--max-memory=16777216', '--strip-all',
            str(obj), '-o', str(binary),
        ], check=True)
        data = binary.read_bytes()
    encoded = base64.b64encode(data).decode('ascii')
    sources = [source, Path(__file__).resolve()]
    import json
    hashes = {str(p.relative_to(source.parent.parent)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources}
    output.write_text(
        '// Generated by wasm/build_panel.py. GPL-2.0-or-later.\n'
        + 'export const sourceHashes = ' + json.dumps(hashes, indent=2) + ';\n'
        + 'export const panelBase64 =\n'
        + ' +\n'.join(repr(encoded[i:i+100]) for i in range(0, len(encoded), 100)) + ';\n'
    )
    print(f'Built {output.name}: {len(data):,} WebAssembly bytes')


if __name__ == '__main__':
    main()
